"""Writes the list of words players are offered to draw (three at a time):
src/data/drawWords.ts for the game and supabase/draw_words.sql for the server,
which only accepts doodles of these words. Every starter doodle's word is here.

Usage: draw_words.py <repo dir>
"""
import json
import sys
from pathlib import Path

REPO = Path(sys.argv[1])
WORDS = """
sun moon star cloud rain snow rainbow lightning tornado volcano mountain island beach wave river tree flower
leaf grass cactus mushroom apple banana grapes cherry lemon orange pear pineapple watermelon carrot corn pumpkin
tomato potato pizza burger sandwich cake cookie donut candy lollipop bread cheese egg icecream popcorn soup
cup mug teapot bottle fork spoon plate bowl kettle pan oven fridge toaster blender candle lamp chair table bed
sofa door window house castle tent igloo bridge tower church lighthouse windmill fence ladder stairs chimney
car bus truck train bicycle motorcycle scooter boat ship submarine rocket airplane helicopter balloon parachute
tractor ambulance taxi skateboard wheel anchor
cat dog fish bird owl duck chicken penguin parrot eagle snake frog turtle rabbit mouse horse cow pig sheep goat
lion tiger elephant giraffe zebra monkey bear panda kangaroo camel whale dolphin shark octopus crab snail spider
bee butterfly ladybug ant worm dinosaur dragon unicorn
hat cap crown helmet glasses sunglasses shoe boot sock glove scarf shirt dress umbrella backpack suitcase
ring necklace watch key lock clock bell hammer saw scissors pencil crayon brush ruler book envelope gift
kite ball balloon drum guitar piano trumpet violin robot camera phone computer television radio battery bulb
magnet compass map flag trophy medal heart smile ghost skeleton snowman mermaid pirate wizard king queen
alien astronaut angel diamond money coin treasure bomb sword shield bow arrow
football basketball tennis golf bowling swing slide seesaw sandcastle
toothbrush comb soap towel bathtub shower toilet mirror
""".split()
BLOCK = {"bomb", "sword", "church", "skeleton", "angel", "toilet", "pirate", "money"}
seen, words = set(), []
for w in WORDS:
    if w in seen or w in BLOCK or not (3 <= len(w) <= 12) or not w.isalpha():
        continue
    seen.add(w)
    words.append(w)

seeds = json.loads((REPO / "src/data/seedPreview.json").read_text())
missing = [w for w in seeds if w not in seen]
assert not missing, f"seed words missing from the draw list: {missing}"

(REPO / "src/data/drawWords.ts").write_text(
    "// Generated by scripts/draw_words.py — the words players are offered to draw.\n"
    "// The server only accepts doodles of these words (doodlezy_words).\n"
    f"export const DRAW_WORDS = {json.dumps(words)};\n"
)
values = ",\n".join(f"  ('{w}')" for w in words)
(REPO / "supabase/draw_words.sql").write_text(
    "-- Words players can be asked to draw (generated by scripts/draw_words.py).\n"
    "insert into public.doodlezy_words (word) values\n" + values + "\non conflict (word) do nothing;\n"
)
print(len(words), "draw words")
